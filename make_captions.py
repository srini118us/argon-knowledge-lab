"""Generate frozen text captions for each diagram, once, with Gemini 3.8 Flash.

Used by arm R2 (indexed as text) and by the agent's read_doc tool. Captions
are written to corpus/<size>/captions and must be committed before any test
run; they are part of the frozen inputs. Existing captions are never
overwritten unless --force is given.

    python make_captions.py
"""
from __future__ import annotations

import argparse
import base64
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CAPTION_MODEL = "gemini-3.8-flash"
PROMPT = ("Describe this architecture diagram completely and literally as text, so that someone who cannot see it "
          "can answer questions about it. List every node, every arrow with its direction and label, every grouping "
          "or boundary with its label, and the diagram title. Do not infer anything that is not drawn.")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", default="small")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    if not os.getenv("GEMINI_API_KEY"):
        sys.exit("GEMINI_API_KEY is not set.")
    from google import genai
    client = genai.Client()
    src = ROOT / "corpus" / args.size / "diagrams"
    dst = ROOT / "corpus" / args.size / "captions"
    dst.mkdir(exist_ok=True)
    for png in sorted(src.glob("*.png")):
        out = dst / f"{png.stem}.txt"
        if out.exists() and not args.force:
            print(f"{png.stem}: exists, kept")
            continue
        ix = client.interactions.create(
            model=CAPTION_MODEL,
            input=[{"type": "image", "data": base64.b64encode(png.read_bytes()).decode(), "mime_type": "image/png"},
                   {"type": "text", "text": PROMPT}],
            generation_config={"thinking_level": "low"})
        out.write_text(f"Caption of {png.stem} (generated by {CAPTION_MODEL}):\n\n{ix.output_text.strip()}\n", encoding="utf-8")
        print(f"{png.stem}: {len(ix.output_text)} chars")
    return 0


if __name__ == "__main__":
    sys.exit(main())
