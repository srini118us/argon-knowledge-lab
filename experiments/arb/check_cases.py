"""Offline validation and key freezing for Experiment 2. No API calls.

    python experiments/arb/check_cases.py            # validate only
    python experiments/arb/check_cases.py --write    # validate, then write spec/key.json

Checks:
  1. Every clause, waiver and contract the engine can cite exists in the pack under the right document.
  2. Numbers in the pack match spec/policy.json (retention limits, waiver dates, freeze window).
  3. Each rendered proposal mentions every structured attribute (no hidden information).
  4. Necessity: for reject and approve_with_conditions cases, at least 3 skipped reasoning steps change
     the outcome; for approve cases, at least 2 over applied rules change it. So no case is a lookup.
  5. Balance: the test split mixes all three decisions.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter

import arb
import engine

MIN_SKIP, MIN_OVER = 3, 2


def pack_docs() -> dict[str, str]:
    """Map DOC_ID@VERSION to its section of the pack."""
    text = arb.pack_text()
    parts = re.split(r"(?m)^# ([A-Z0-9-]+@[A-Za-z0-9.-]+):", text)
    return {parts[i]: parts[i + 1] for i in range(1, len(parts), 2)}


def check_pack(policy: dict) -> list[str]:
    docs, problems = pack_docs(), []
    for rid, r in policy["rules"].items():
        if r["doc"] not in docs or f"**{rid}**" not in docs[r["doc"]]:
            problems.append(f"rule {rid} not found in {r['doc']}")
    for wid, w in policy["waivers"].items():
        body = docs.get(w["doc"], "")
        line = next((l for l in body.splitlines() if l.startswith(f"**{wid}**")), "")
        if not line:
            problems.append(f"waiver {wid} not in {w['doc']}")
            continue
        for k in ("valid_from", "valid_to"):
            if w[k] not in line:
                problems.append(f"waiver {wid}: {k} {w[k]} not stated")
        if w["rule"] not in line or w["vendor"] not in line:
            problems.append(f"waiver {wid}: rule or vendor not stated")
    for v in policy["vendors"].values():
        if v["contract"] not in docs:
            problems.append(f"contract {v['contract']} missing")
    if "30 days" not in docs["SEC-POL@v3"] or "14 days" not in docs["AX-EU@v1"] or "90 days" not in docs["SEC-POL@v2"]:
        problems.append("retention numbers in pack do not match policy.json")
    fw = policy["freeze_windows"][0]
    if fw["start"] not in docs["CHG-CAL@2026"] or fw["end"] not in docs["CHG-CAL@2026"]:
        problems.append("freeze window dates do not match")
    return problems


def check_case(case: dict) -> tuple[dict, list[str], list[str], list[str]]:
    base_r = engine.evaluate(case)
    base = engine.outcome(base_r)
    skip = [m for m in engine.SKIP if engine.outcome(engine.evaluate(case, mutation=m)) != base]
    over = [m for m in engine.OVER if engine.outcome(engine.evaluate(case, mutation=m)) != base]
    problems = []
    text = arb.render(case)
    for f in case["fields"]:
        if arb.FIELD_NAMES[f] not in text:
            problems.append(f"{case['id']}: field {f} not rendered")
    for needle in (case["vendor"], case["go_live"], f"{case['retention_days']} days", case["source_zone"]):
        if needle not in text:
            problems.append(f"{case['id']}: {needle} not rendered")
    if base_r["decision"] == "approve":
        if len(over) < MIN_OVER:
            problems.append(f"{case['id']}: approve case has only {len(over)} traps")
    elif len(skip) < MIN_SKIP:
        problems.append(f"{case['id']}: only {len(skip)} necessary steps")
    return base_r, skip, over, problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="write spec/key.json when all checks pass")
    args = ap.parse_args()
    policy = engine.load_policy()
    problems = check_pack(policy)
    key, decisions = {}, Counter()
    for c in arb.load_cases():
        r, skip, over, p = check_case(c)
        problems += p
        key[c["id"]] = r | {"split": c["split"], "necessary_steps": skip, "traps": over}
        if c["split"] == "test":
            decisions[r["decision"]] += 1
        print(f"{c['id']:5s} {r['decision']:24s} viol={r['violations']} cond={r['conditions']} "
              f"steps={len(skip)} traps={len(over)}")
    if len(decisions) < 3:
        problems.append(f"test split does not cover all decisions: {dict(decisions)}")
    print(f"\nTest decisions: {dict(decisions)}")
    print(f"Pack: {len(arb.pack_text()):,} characters (~{len(arb.pack_text()) // 4:,} tokens)")
    if problems:
        print("\nPROBLEMS:\n  " + "\n  ".join(problems))
        return 1
    print("All checks passed.")
    if args.write:
        (arb.SPEC / "key.json").write_text(json.dumps({"_note": "Generated by check_cases.py from engine.py; do not edit.",
                                                       "key": key}, indent=1) + "\n", encoding="utf-8")
        print("Wrote spec/key.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
